"""Emitter: ``paper/generated/pyun_macros.tex`` (plain names; numbers only).

Replication (official lines, Pyun's entries, VW-CRSP market-adjusted): ``\\PyunRep<Quantity><H>``
with Quantity in {TxnMean, FilingMean, Diff} and H in {Five, Ten, Twenty, Thirty, Sixty, OneTwenty};
``\\PyunRep<Quantity>`` alone is the 30-session value (Pyun's Table 3 headline horizon), with
``Se`` (household x filing month), ``SeBlock``, ``T``, ``N`` and ``Households`` suffixes.
Bridge: ``\\PyunBridgeStep<K><Quantity>[Se|N]`` for every computed row and quantity, with K the
step id spelled out (One, Two, ..., EightA, EightB, ..., ThirteenB) and Quantity in
{TxnMean, FilingMean, Diff, DiffPooled, SpreadPublic, SpreadTxn}. Sample counts: ``\\PyunSample<Name>``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from trading_on_disclosure_v4.existing.macros import fmt_num
from trading_on_disclosure_v4.outcomes import panel

TEX_PATH = panel.REPO_ROOT / "paper" / "generated" / "pyun_macros.tex"
H_NAMES = {5: "Five", 10: "Ten", 20: "Twenty", 30: "Thirty", 60: "Sixty", 120: "OneTwenty"}
Q_NAMES = {"T_mean": "TxnMean", "P_mean": "FilingMean", "TP_diff": "Diff", "TP_diff_all": "DiffPooled",
           "P_spread": "SpreadPublic", "T_spread": "SpreadTxn"}
STEP_NAMES = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven",
              "8a": "EightA", "8b": "EightB", "9": "Nine", "10": "Ten", "11a": "ElevenA", "12a": "TwelveA", "13a": "ThirteenA",
              "11b": "ElevenB", "12b": "TwelveB", "13b": "ThirteenB"}


def fmt_int(x) -> str:
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{int(x):,}"


def replication_macros(rep: pd.DataFrame) -> list[tuple[str, str]]:
    out = []
    sub = rep[(rep["record"] == "official") & (rep["entry"] == "pyun") & (rep["bench"] == "vw") & (~rep["winsor"])]
    for r in sub.itertuples():
        base = f"PyunRep{Q_NAMES[r.quantity]}{H_NAMES[int(r.h)]}"
        out += [(base, fmt_num(r.estimate_bp)), (base + "Se", fmt_num(r.se_pyun)), (base + "SeBlock", fmt_num(r.se_block)),
                (base + "T", fmt_num(r.t_pyun)), (base + "N", fmt_int(r.n_events)), (base + "Households", fmt_int(r.n_households))]
        if int(r.h) == 30:
            short = f"PyunRep{Q_NAMES[r.quantity]}"
            out += [(short, fmt_num(r.estimate_bp)), (short + "Se", fmt_num(r.se_pyun)), (short + "SeBlock", fmt_num(r.se_block)),
                    (short + "T", fmt_num(r.t_pyun)), (short + "N", fmt_int(r.n_events)), (short + "Households", fmt_int(r.n_households)),
                    (short + "PerTwenty", fmt_num(r.estimate_bp_per20))]
    return out


def bridge_macros(table: pd.DataFrame) -> list[tuple[str, str]]:
    out = []
    for r in table[table["quantity"] != ""].itertuples():
        base = f"PyunBridgeStep{STEP_NAMES[str(r.step)]}{Q_NAMES[r.quantity]}"
        out += [(base + "Estimate", fmt_num(r.estimate_bp)), (base + "PerTwenty", fmt_num(r.estimate_bp_per20)),
                (base + "Se", fmt_num(r.se_headline)), (base + "SeBlock", fmt_num(r.se_block)), (base + "N", fmt_int(r.n_events)),
                (base + "Households", fmt_int(r.n_households))]
    return out


def sample_macros(report: dict) -> list[tuple[str, str]]:
    out = []
    for record, name in (("all", "All"), ("official", "Official"), ("dedup", "Dedup")):
        for k, suffix in (("paired_lines", "Lines"), ("purchases", "Purchases"), ("sales", "Sales"), ("households", "Households")):
            out.append((f"PyunSample{name}{suffix}", fmt_int(report[record][k])))
    ln = report["lines"]
    for k, suffix in (("vendor_duplicate_lines", "VendorDuplicateLines"), ("transaction_date_not_a_session", "TxnDateNotSession"),
                      ("public_anchor_ours_one_session_after_pyun", "PublicAnchorOneSessionLater"), ("lag_1_365_within_period", "LagInRange"),
                      ("both_dates_2015_2025", "BothDatesInPeriod")):
        out.append((f"PyunSample{suffix}", fmt_int(ln[k])))
    return out


def write(rep: pd.DataFrame, table: pd.DataFrame, report: dict | None = None, path: Path = TEX_PATH) -> list[tuple[str, str]]:
    macros = replication_macros(rep) + bridge_macros(table) + (sample_macros(report) if report else [])
    names = [m for m, _ in macros]
    if len(names) != len(set(names)):
        raise ValueError("duplicate macro names")
    lines = ["% generated by trading_on_disclosure_v4.pyun.macros; numbers only, do not edit"]
    lines += [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return macros
