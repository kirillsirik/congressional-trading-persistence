def spread_table():
    d = read_csv("data/v4/existing/appendix_dedup/horizons.csv")
    d = d[d["sample"] == "dedup"].sort_values("horizon")
    assert list(d.horizon) == [5, 10, 20, 40, 60, 127]
    assert list(d.n) == [40221, 40184, 39724, 39233, 38654, 37024]
    counts = read_csv("data/v4/existing/table1_dedup.csv").set_index("field")["dedup"]
    assert (int(counts.households_h20), int(counts.blocks_h20)) == (325, 157)
    lines = [r"\begin{table}[H]", r"\centering", r"\begin{threeparttable}",
             r"\caption{Purchase-minus-sale returns after disclosure, 2014--2026}", r"\label{tab:primary}", r"\small",
             r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lS[table-format=-2.1]S[table-format=2.1]cS[table-format=5.0]@{}}",
             r"\toprule", r"\shortstack[l]{Horizon\\(trading days)} & {\shortstack{Spread\\(bp)}} & {\shortstack{SE\\(bp)}} & \shortstack{95\% interval\\(bp)} & {Signals}\\", r"\midrule"]
    for row in d.itertuples():
        horizon = f"{row.horizon}" + (" (baseline)" if row.horizon == 20 else "")
        ci = rf"$[{row.ci_low_block:.1f},\,{row.ci_high_block:.1f}]$"
        lines.append(f"{horizon} & {row.estimate:.1f} & {row.se_block:.1f} & {ci} & {integer(row.n)} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular*}", r"\begin{tablenotes}[flushleft]\footnotesize\raggedright",
              '\\item \\textit{Notes:} The spread is the mean market-adjusted purchase return minus the mean market-adjusted sale return, in bp. Returns begin at the first close after the assigned disclosure date, and each horizon uses the signals with complete returns over that horizon. Standard errors cluster by household and 20-day entry block. At the 20-trading-day horizon there are 325 households and 157 entry blocks; 89 of the households have only sales, and their signals enter the sale mean. Confidence intervals use a Student critical value with degrees of freedom equal to the smaller cluster count minus one.',
              r"\end{tablenotes}", r"\end{threeparttable}", r"\end{table}"]
    write("table02_average.tex", "\n".join(lines) + "\n")
    return d[["horizon", "estimate", "se_block", "ci_low_block", "ci_high_block", "n"]].to_dict("records")


