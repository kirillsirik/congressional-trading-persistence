    assert (other_assets, unknown_assets, unmatched_common, missing_date) == (19374, 9702, 1607, 3)
    # Table A1 (set in the paper) splits the unmatched records by reason
    by_category = classification.groupby("category")["n"].sum()
    assert (int(by_category["not_on_crsp"]) - missing_date, int(by_category["unclassified_no_ticker"]),
            int(by_category["date_invalid"]), int(classification["n"].sum())) == (4664, 4506, 532, 30686)
