def household_figure():
    d = read_csv("data/v4/round2/closeout/closeout_2026-11-10/inputs/benchmark_figure.csv")
    means = read_csv("data/v4/round2/closeout/closeout_2026-11-10/inputs/principal_household_means.csv")
    assert set(d.clock) == {"T"} and set(d.outcome_transform) == {"separately_winsorized"}
    panels = {}
    for benchmark in ("intercept_omitted", "fitted_intercept"):
        g = d[d.benchmark == benchmark].sort_values("household_index").reset_index(drop=True)
        assert len(g) == 38 and g.household_index.is_unique
        w = g.weight.to_numpy(float)
        c = np.column_stack([np.ones(len(g)), g.activity_log.to_numpy(float)])
        m = g[["period_A_mean_bp", "period_B_mean_bp"]].to_numpy(float)
        z = m - c @ np.linalg.solve(c.T @ (w[:, None] * c), c.T @ (w[:, None] * m))
        x, y = z.T
        cov = np.sum(w * x * y) / w.sum()
        slope = np.sum(w * x * y) / np.sum(w * x * x)
        panels[benchmark] = {"ids": g.household_index.to_numpy(), "x": x, "y": y, "w": w, "cov": cov, "slope": slope}
    np.testing.assert_array_equal(panels["fitted_intercept"]["ids"], panels["intercept_omitted"]["ids"])
    np.testing.assert_allclose(panels["fitted_intercept"]["w"], panels["intercept_omitted"]["w"], rtol=0, atol=0)
    results = read_csv("data/v4/results.csv")
    for name, (analysis, variant) in {"fitted_intercept": ("tau", "event_share"), "intercept_omitted": ("robustness", "no_alpha")}.items():
        frozen = results[(results.clock == "T") & (results.analysis == analysis) & (results.variant == variant) & (results.statistic == "tau2")].value
        assert len(frozen) == 1
        np.testing.assert_allclose(panels[name]["cov"], frozen.iloc[0], rtol=1e-10)
    p = panels["fitted_intercept"]
    contribution = p["w"] * p["x"] * p["y"] / p["w"].sum()
    influential = int(p["ids"][np.argmax(contribution)])
    h = means[(means.clock == "T") & (means.scale == "winsorized") & (means.household_index == influential)]
    n = int((h.n_A + h.n_B).iloc[0])
    idx = int(np.flatnonzero(p["ids"] == influential)[0])
    weight_pct = 100 * p["w"][idx] / p["w"].sum()
    assert n == 535 and round(weight_pct, 1) == 7.0 and p["x"][idx] < 0 and p["y"][idx] < 0
    fig, axes = plt.subplots(1, 2, figsize=(6.5, 3.25), sharex=True, sharey=True)
    fig.subplots_adjust(left=.105, right=.985, bottom=.21, top=.89, wspace=.14)
    for ax, (name, p), title, color in zip(axes, panels.items(), ["(a) Factor-only benchmark", "(b) Event-study benchmark"], [".3", ".3"], strict=True):
        ax.scatter(p["x"], p["y"], s=170 * p["w"] / p["w"].max(), color=color, edgecolors="white", linewidths=.45, alpha=.85, zorder=3)
        grid = np.array([-400, 250])
        ax.plot(grid, grid * p["slope"], color=".1", lw=1.1, zorder=2)
        ax.axhline(0, color=".72", lw=.6, zorder=1)
        ax.axvline(0, color=".72", lw=.6, zorder=1)
        i = int(np.flatnonzero(p["ids"] == influential)[0])
        ax.scatter([p["x"][i]], [p["y"][i]], s=195 * p["w"][i] / p["w"].max(), facecolors="none", edgecolors="black", lw=1.0, zorder=4)
        label = "Largest contributor\n535 purchases; 7.0% weight" if name == "fitted_intercept" else "Same household"
        position = (-385, 245) if name == "fitted_intercept" else (-380, -315)
        ax.annotate(label, xy=(p["x"][i], p["y"][i]), xytext=position, ha="left", va="center", fontsize=7.8,
                    arrowprops={"arrowstyle": "->", "lw": .75, "connectionstyle": "angle3,angleA=-90,angleB=180" if name == "fitted_intercept" else "angle3,angleA=0,angleB=-90"}, zorder=5,
                    bbox={"fc": "white", "ec": "none", "pad": 1})
        ax.text(.04, .94, f"Slope = {p['slope']:.2f}".replace("-", "−"), transform=ax.transAxes, ha="left", va="top", fontsize=9,
                bbox={"fc": "white", "ec": "none", "pad": 1})
        ax.set(xlim=(-400, 250), ylim=(-450, 450), xlabel="Early mean, 2015–2020 (bp)")
        ax.xaxis.set_major_locator(MultipleLocator(200))
        ax.yaxis.set_major_locator(MultipleLocator(200))
        ax.set_title(title, loc="left", fontsize=9, pad=7)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    axes[0].set_ylabel("Late mean, 2021–2025 (bp)")
    save_figure(fig, "households")
    write("figure02_households.tex", r"""\begin{figure}[H]
\centering
\includegraphics[width=\textwidth]{figures/writing_sample_households.pdf}
\caption{Household purchase returns in 2015--2020 and 2021--2025 under two benchmarks. Each point represents one of the 38 households in the persistence sample. Both panels use the same 7,964 purchases, and each period's means are residuals from a weighted regression on early trading activity. Point area is proportional to the geometric-mean weight, and lines are weighted regression fits with the slopes of Table~\ref{tab:tau}. The labeled household has negative residual means in both periods under both benchmarks and makes the largest contribution to the event-study covariance.}
\label{fig:benchmark-persistence}
\end{figure}
""")
    return {"panel_order": list(panels), "influential_household": influential, "purchases": n, "weight_percent": weight_pct,
            "panels": {name: {k: v.tolist() if isinstance(v, np.ndarray) else v for k, v in values.items()} for name, values in panels.items()}}


def power_figure():
    data = read_csv("data/v4/ext/activity_power_surface.csv")
    styles = [("most_active", "Most active", ".08", "o", "-"), ("random", "Uniformly chosen household", ".35", "s", "--"), ("least_active", "Least active", ".55", "^", ":")]
    fig, ax = plt.subplots(figsize=(6.5, 2.35))
    fig.subplots_adjust(left=.10, right=.98, bottom=.19, top=.87)
    output = {}
    for selection, label, color, marker, linestyle in styles:
        rows = data[(data.clock == "T") & (data.k == 1) & (data.test == "T3") & (data.selection == selection)].sort_values("mu_bp")
        assert list(rows.mu_bp) == [50, 100, 200, 400, 800, 1600] and (rows.n_panels == 500).all()
        x, y = rows.mu_bp.to_numpy(float), rows.power.to_numpy(float)
        j = int(np.flatnonzero(y >= .8)[0])
        assert j > 0 and y[j] > y[j - 1]
        threshold = np.exp(np.log(x[j - 1]) + (.8 - y[j - 1]) / (y[j] - y[j - 1]) * (np.log(x[j]) - np.log(x[j - 1])))
        ax.plot(x, 100 * y, label=label, color=color, marker=marker, linestyle=linestyle, linewidth=1.5, markersize=4.5, zorder=3)
        ax.plot([threshold, threshold], [0, 80], color=color, lw=.7, linestyle=(0, (2, 3)), zorder=1)
        ax.plot(threshold, 80, marker=marker, color=color, markersize=5.5, zorder=4)
        ax.annotate(f"{threshold:,.0f} bp", (threshold, 80), xytext=((6, -17) if selection != "least_active" else (-5, -17)), textcoords="offset points",
                    ha="left" if selection != "least_active" else "right", fontsize=9,
                    bbox={"fc": "white", "ec": "none", "pad": 1})
        output[selection] = {"gains_bp": x.tolist(), "rejection_rates": y.tolist(), "threshold_bp": threshold}
    assert [round(output[s]["threshold_bp"]) for s, *_ in styles] == [155, 336, 1489]
    ax.axhline(80, color=".4", lw=.8, linestyle="--", zorder=0)
