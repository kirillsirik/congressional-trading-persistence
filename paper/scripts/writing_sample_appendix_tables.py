        cells=[label,x['n_households']]
        for b in ['fo','es']:
            mark=r'\textsuperscript{\ensuremath{\dagger}}' if x[b+'_psd'].lower()=='true' else ''
            lo,hi=x[b+'_boot_lo'],x[b+'_boot_hi']
