# Paired inference: every heuristic degree of freedom is printed in its cell.
d=read(S/'S5_conclusion_matrix.csv')
def row(clock,stat,method):
    z=[r for r in d if r['clock']==clock and r['statistic']==stat and r['method']==method]
    assert len(z)==1,(clock,stat,method)
    return z[0]
def icell(z):return interval(z['ci_low'],z['ci_high'])
def nucell(z):return r'{\scriptsize $\nu='+fmt(z['df'],2)+'$}'
ls=[r'\footnotesize\setlength{\tabcolsep}{3pt}',r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}>{\raggedright\arraybackslash}p{2.65cm}r c c c c@{}}',r'\toprule',r'Quantity & Estimate & \shortstack{Bootstrap\\interval} & \shortstack{Jackknife\\ordinary\\household count} & \shortstack{Jackknife\\selected effective\\cluster count} & \shortstack{Jackknife\\smaller of the two\\benchmark counts}\\',r'\midrule']
for clock,title in [('T','Trade date: 38 households'),('P','Disclosure date: 30 households')]:
    ls.append(r'\multicolumn{6}{l}{\textit{'+title+r'}}\\')
    for stat,label in [('gap','Benchmark gap'),('recurrence_KDD','Charge covariance')]:
        a=row(clock,stat,'paired household bootstrap percentile')
        b=row(clock,stat,'jackknife t(G-1)')
        c=row(clock,stat,'jackknife t(G*_event_study - 1) heuristic' if stat=='gap' else 'jackknife t(G*_recurrence - 1)')
        e=row(clock,stat,'jackknife t(min endpoint G* - 1) heuristic' if stat=='gap' else 'jackknife t(min endpoint G* - 1) sensitivity')
        # Degrees of freedom sit on their own line so that every interval shares its row's baseline.
        ls.append(' & '.join([label,r'\ensuremath{'+m(a['estimate'])+'}',icell(a),icell(b),icell(c),icell(e)])+r'\\')
        ls.append(' & '.join(['','','','',nucell(c),nucell(e)])+r'\\[4pt]')
    ls.append(r'\addlinespace')
ls.extend([r'\bottomrule',r'\end{tabular*}']);out('appendix_paired_inference.tex',ls)

