#!/usr/bin/env python3
"""Table C2 (standard errors under alternative clustering), from the stored inference ladders.

writing_sample_appendix_tables.py relabels the rows of the table body this writes; never estimates models."""
import argparse, csv, hashlib, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'paper/revised_generated'
LEDGER = {'source_hashes': {}, 'tables': {}}
BANNER = '% Generated by paper/scripts/annals_closeout_tables.py; presentation only.\n'
outputs = {}
def read(path):
    data = (ROOT / path).read_bytes()
    LEDGER['source_hashes'][path] = hashlib.sha256(data).hexdigest()
    return data.decode()
def emit(name, text, sources):
    outputs[name + '.tex'] = BANNER + text
    LEDGER['tables'][name] = sources
# Rebuild headers, grouping, and labels; empirical cells are copied verbatim.
def table(cols, header, body):
    tokens=re.findall(r">\{(?:[^{}]|\{[^{}]*\})*\}p\{[^}]+\}|p\{[^}]+\}|[lrc]",cols)
    data=[x[:-2].strip().split(' & ') for x in body if x.endswith(r'\\') and not x.startswith(r'\multicolumn')]
    numeric=[];specs=[]
    for j,token in enumerate(tokens):
        vals=[r[j] for r in data if r[j] not in (r'\textemdash','--','NR')]
        ok=vals and all(re.fullmatch(r'-?[\d,]+(?:\.\d+)?',v) for v in vals)
        numeric.append(bool(ok))
        if ok:
            digits=max(len(v.lstrip('-').replace(',','').split('.')[0]) for v in vals)
            dec=max(len(v.split('.')[1]) if '.' in v else 0 for v in vals)
            specs.append('S[table-format='+('-' if any(v.startswith('-') for v in vals) else '')+str(digits)+'.'+str(dec)+']')
        else:specs.append(token if token!='r' else 'c')
    hh=[]
    for h in header:
        parts=re.split(r'\s*&\s*',h[:-2].strip()) if h.endswith(r'\\') else []
        if len(parts)==len(tokens):h=' & '.join(r'\multicolumn{1}{c}{'+v+'}' if numeric[j] and not v.startswith(r'\multicolumn') else v for j,v in enumerate(parts))+r' \\'
        hh.append(h)
    bb=[]
    for line in body:
        parts=line[:-2].strip().split(' & ') if line.endswith(r'\\') and not line.startswith(r'\multicolumn') else []
        if len(parts)==len(tokens):
            for j,v in enumerate(parts):
                if numeric[j] and v in (r'\textemdash','--','NR'):parts[j]='{'+(r'\textemdash' if v=='--' else v)+'}'
                elif not numeric[j] and re.fullmatch(r'[-\d., ]+\([-\d., ]+\)',v):parts[j]=r'\ensuremath{'+v.replace(',',r'{,}')+'}'
            line=' & '.join(parts)+r' \\'
        bb.append(line)
    return '\n'.join([r'\begingroup',r'\sisetup{group-separator={,},group-minimum-digits=4,input-ignore={,}}',r'\begin{tabular}{@{}'+''.join(specs)+r'@{}}',r'\toprule',*hh,r'\midrule',*bb,r'\bottomrule',r'\end{tabular}',r'\endgroup'])+'\n'

def row(cells): return ' & '.join(cells)+r' \\'

def pick(rows, **key):
    found = [r for r in rows if all(r[k] == v for k,v in key.items())]
    assert len(found) == 1, (key,len(found))
    return found[0]
pinitial='data/v4/ext/inference_ladder.csv';pext='data/v4/final/spread_corrected.csv'
ri=list(csv.DictReader(read(pinitial).splitlines()));rext=list(csv.DictReader(read(pext).splitlines()))
body=[];evidence=[]
for stat,label in [('household_x_day','Entry day'),('household_x_block20','20-session entry block'),('household_x_block40','40-session entry block'),('household_x_block60','60-session entry block'),('household_x_quarter','Calendar quarter'),('household_x_block20_x_security','20-session entry block and security'),('household_x_block60_x_security','60-session entry block and security')]:
    aa=pick(ri,clock='P',variant='public_spread_dedup',statistic=stat)
    bb=pick(rext,clock='P',analysis='spread_ladder',variant='corrected_july_delisting_reinvested',statistic=stat)
    cc=pick(ri,clock='T',variant='tau2_headline',statistic=stat);dd=pick(ri,clock='P',variant='tau2_headline',statistic=stat)
    body.append(row([label,*[f"{float(x['se_block']):.2f}" for x in (aa,bb)],*[f"{float(x['se_block']):,.0f}" for x in (cc,dd)]]))
    evidence.append({'statistic':stat,'initial_spread':aa['se_block'],'extended_spread':bb['se_block'],'trade_covariance':cc['se_block'],'disclosure_covariance':dd['se_block']})
emit('table20_clustering_merged',table(r'>{\raggedright\arraybackslash}p{3.8cm}rrrr',[r'\shortstack[l]{Clustering in addition\\to household} & \shortstack{Spread SE,\\initial sample\\(bp)} & \shortstack{Spread SE,\\extended sample\\(bp)} & \shortstack{Trade-date\\covariance SE\\($\mathrm{bp}^2$)} & \shortstack{Disclosure-date\\covariance SE\\($\mathrm{bp}^2$)} \\'],body),{'source':[pinitial,pext],'cells':evidence})
outputs['closeout_table_sources.json']=json.dumps(LEDGER,indent=2)+'\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
    for name,content in outputs.items():
        assert (OUT/name).read_text()==content, f'Stale presentation asset: {name}'
    print(f'PASS: {len(outputs)-1} presentation tables agree with protected source cells.')
else:
    OUT.mkdir(exist_ok=True)
    for name,content in outputs.items(): (OUT/name).write_text(content)
    print(f'Wrote {len(outputs)-1} presentation tables and source ledger.')
