#!/usr/bin/env python3
"""Presentation-only appendix A--D overlays from verified numerical exports."""
from pathlib import Path
import argparse, hashlib, json, re, csv
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT/'paper/revised_generated'

def body(text,name):
    token = re.search(r'\\(?:new|provide|renew)command\{\\'+re.escape(name)+r'\}\{',text)
    if token is None: raise ValueError(name)
    start=token.end(); depth=1
    for i in range(start,len(text)):
        if text[i]=='{': depth+=1
        elif text[i]=='}':
            depth-=1
            if not depth:return text[start:i]
    raise ValueError(name)

def rows(text,name):
    return [line.rstrip().removesuffix('\\\\').rstrip().split(' & ') for line in body(text,name).splitlines() if ' & ' in line]

def join(rows):return '\n'.join(' & '.join(r)+r' \\' for r in rows)
def panel(s,n=6):return r'\addlinespace[3pt]\multicolumn{'+str(n)+r'}{l}{\textit{'+s+r'}} \\'
def numeric_math(s):
    return r'\ensuremath{'+s.replace(', ',r',\,')+'}' if s.startswith('[') else s

def build():
    files={name:(ROOT/'paper/generated'/name).read_text() for name in ('appendix_table_rows.tex','main_table_rows.tex','v4_placeholders.tex')}
    out=['% Generated by abcd_tables.py from verified table cells.']
    sources=[]
    def macro(name,content,new=False):out.append(('\\newcommand' if new else '\\renewcommand')+'{\\'+name+'}{%\n'+content+'\n}')
    date=rows(files['appendix_table_rows.tex'],'IADateUniverseRows')
    date=[[r[0].lstrip('+')]+[c.replace(r'\%','') for c in r[1:]] for r in date]
    # Every original count/share pair appears once in the split panels.
    macro('IADateUniverseRowsA',join([r[:7] for r in date]),True)
    macro('IADateUniverseRowsB',join([[r[0]]+r[7:] for r in date]),True)
    sens=rows(files['appendix_table_rows.tex'],'IASensitivityRows')
    groups={0:'Alternative weighting and observational units',3:'Household identifiers',4:'Return benchmarks'}
    sens_labels=['Records weighted equally','Households weighted equally (households with both directions)','Stock--entry-date cells weighted equally','Household identifiers as reported by each source','CAPM-adjusted returns','Event-study returns (six factors)']
    factor_source=ROOT/'data/v4/writing_sample/tables/tableC1_six_factor_spread.csv'
    factor_rows=list(csv.DictReader(factor_source.open()))
    factor=next(r for r in factor_rows if r['specification'].startswith('Six-factor factor-only'))
    factor_cells=['Factor-only returns (six factors)',f"{float(factor['spread_bp']):.2f}",f"{float(factor['se_bp']):.2f}",r'\ensuremath{['+f"{float(factor['ci_low_bp']):.2f},\\,{float(factor['ci_high_bp']):.2f}"+']}',f"{float(factor['p_value']):.3f}",f"{int(factor['signals']):,}"]
    sources.append({'source':str(factor_source.relative_to(ROOT)),'sha256':hashlib.sha256(factor_source.read_bytes()).hexdigest(),'operation':'Add factor-only counterpart on the same 39,030 signals; identify original event-study benchmark explicitly'})
    transformed=[]
    for i,r in enumerate(sens):
        if i in groups:transformed.append(panel(groups[i]))
        if i==5:transformed.append(join([factor_cells]))
        transformed.append(join([[sens_labels[i]]+[numeric_math(c) for c in r[1:]]]))
    macro('IASensitivityRows','\n'.join(transformed))
    fullrows=list(csv.DictReader((ROOT/'data/v4/existing/appendix_dedup/full_results.csv').open()))
    bytest={r['test_id']:r for r in fullrows if r['sample']=='dedup'}
    def sample_row(key):
        r=bytest[key]
        return ['',f"{float(r['estimate']):.2f}",f"{float(r['se_block']):.2f}",r'\ensuremath{['+f"{float(r['ci_low_block']):.2f},\\,{float(r['ci_high_block']):.2f}"+']}',f"{float(r['p_block']):.3f}",f"{int(r['n']):,}"]
    dates=[sample_row(k) for k in ['TW_P1_E20','TW_P3_RAW_CT','TW_P3_OFFICIAL_ONLY','TW_P3_OFFICIAL_SEGMENT','TW_P3_VENDOR_SEGMENT','TW_P3_ENTRY_PLUS1']]
    labels=['Official filing date; otherwise vendor publication date minus one day (baseline)','Vendor publication date without the one-day adjustment','Signals with an official filing date','Official-source records only','Vendor records with an imputed date','Entry delayed by one further trading day']
    macro('HTableThreeRowsFull',join([[labels[i]]+r[1:] for i,r in enumerate(dates)]))
    clock=[sample_row(k) for k in ['TW_P1_E20','TW_C1_T20','TW_C1_TRAW20','TW_C1_PAIRED']]
    clock[0][0]='Disclosure date'; clock[1][0]='Trade date, standardized reported date';clock[2][0]='Trade date, unadjusted vendor date where available';clock[3][0]='Paired difference, trade date minus disclosure date (purchases and sales)'
    macro('HTableClocksRows',panel('Purchase-minus-sale spreads')+'\n'+join(clock[:3])+'\n'+panel('Mean paired signal difference')+'\n'+join(clock[3:]))
    account=rows(files['main_table_rows.tex'],'TableSixInferenceRows')
    account_labels=['Mean account excess return','CAPM alpha','Six-factor alpha']
    assert {r[-1] for r in account}=={'3,497'}
    macro('ABCDAccountInferenceRows',join([[account_labels[i]]+[numeric_math(c) for c in r[1:-1]] for i,r in enumerate(account)]),True)
    fullpath=ROOT/'data/v4/existing/appendix_dedup/full_results.csv'
    full=list(csv.DictReader(fullpath.open()))
    mappings={'TW_P1_E20':'Primary','TW_P2_E5':'HorizonFive','TW_P2_E10':'HorizonTen','TW_P2_E40':'HorizonForty','TW_P2_E60':'HorizonSixty','TW_P2_E127':'HorizonOneTwentySeven','TW_P3_RAW_CT':'RawVendorDates','TW_P3_OFFICIAL_ONLY':'OfficialDates','TW_P3_OFFICIAL_SEGMENT':'OfficialSource','TW_P3_VENDOR_SEGMENT':'VendorSource','TW_P3_ENTRY_PLUS1':'EntryPlusOne','TW_C1_T20':'TransactionClock','TW_C1_TRAW20':'TransactionClockRawDates','TW_C1_PAIRED':'PairedClocks','TW_D_SAR20':'SignedPayoff','TW_S2_CAPM':'Capm','TW_S2_FF5MOM':'FiveFactorMomentum','TW_S1_RAWROWS':'RawRows','TW_S1_SRCID':'SourceNativeIds','TW_S1_EQHH':'EqualHousehold','TW_S1_EVENT':'EventLevel'}
    pvalues=[]
    for r in full:
        if r['sample']=='dedup' and r['test_id'] in mappings:
            name='ExDedup'+mappings[r['test_id']]+'PBlock'
            out.append('\\providecommand{\\'+name+'}{}')
            macro(name,f"{float(r['p_block']):.3f}")
            pvalues.append({'macro':name,'test_id':r['test_id'],'p_block':r['p_block']})
    sourcepath='data/v4/existing/appendix_dedup/full_results.csv'
    sources.append({'source':sourcepath,'sha256':hashlib.sha256(fullpath.read_bytes()).hexdigest(),'pvalue_rounding':pvalues})
    for name,text in files.items():sources.append({'source':'paper/generated/'+name,'sha256':hashlib.sha256(text.encode()).hexdigest()})
    manifest={'sources':sources,'operations':{'table16':'split five count/share populations into panels, preserving every cell','table17':'labels only','table18':'labels, three panels, math-mode numeric cells, and source-backed factor-only counterpart','table19':'panels and labels only','table21':'labels, math-mode numeric cells; common N=3497 moved to note'},'numerical_changes':['p-values displayed to three decimals from unchanged unrounded source values','Added factor-only spread -6.09, SE 10.36, interval [-26.56,14.38], p=0.558, N=39,030 from the verified computation return; retained original event-study values']}
    return {'abcd_overrides.tex':'\n'.join(out)+'\n','abcd_table_sources.json':json.dumps(manifest,indent=2)+'\n'}
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for name,content in build().items():
        p=OUT/name
        if args.check:assert p.read_text()==content, f'Stale presentation fragment: {p}'
        else:p.write_text(content)
    print('PASS: A-D presentation overlays generated from verified source cells.')
